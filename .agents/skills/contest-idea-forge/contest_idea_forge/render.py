"""Step 4 (code): turn the analysis results into deliverables.

Always writes Markdown + JSON. Optionally pushes a Notion page when
NOTION_TOKEN and a parent page id are configured. All formatting is
deterministic — no model calls here.
"""
from __future__ import annotations

import json
import os
import urllib.request
from pathlib import Path

CIRCLED = ["①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧", "⑨", "⑩"]


def _esc(v) -> str:
    return str(v if v is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _as_lines(v) -> list[str]:
    if isinstance(v, list):
        return [str(x) for x in v]
    if v in (None, ""):
        return []
    return [str(v)]


def _overview_table(contest: dict) -> list[str]:
    rows = [
        ("공모명", contest.get("name")),
        ("주최/주관", contest.get("host")),
        ("분야", contest.get("field")),
        ("공모 주제", contest.get("theme")),
        ("접수 마감", contest.get("deadline")),
        ("참가 자격", contest.get("eligibility")),
        ("팀 규칙", contest.get("team_rule")),
        ("필수/활용 데이터", contest.get("required_data")),
        ("일정", contest.get("schedule")),
        ("원본 링크", contest.get("source_url")),
    ]
    out = ["| 항목 | 내용 |", "| --- | --- |"]
    out += [f"| {k} | {_esc(v)} |" for k, v in rows if v]
    return out


def _idea_body(idea: dict, verdict: dict | None) -> list[str]:
    L: list[str] = [f"> {idea.get('one_liner','')}", ""]
    fm = idea.get("field_mapping")
    if fm:
        L += ["**가점/공모 분야**: " + ", ".join(_as_lines(fm)), ""]
    blocks = [
        ("해결하려는 문제", idea.get("problem")),
        ("접근 방법", idea.get("approach")),
        ("사용 데이터 / 테스트베드", idea.get("data_used")),
    ]
    for h, v in blocks:
        if v:
            L += [f"### {h}", str(v), ""]
    if idea.get("core_features"):
        L += ["### 핵심 기능"] + [f"- {x}" for x in _as_lines(idea["core_features"])] + [""]
    if idea.get("demo_scope"):
        L += ["### 데모(MVP) 범위", str(idea["demo_scope"]), ""]
    if idea.get("tech_stack"):
        L += ["### 기술 스택", ", ".join(_as_lines(idea["tech_stack"])), ""]
    if idea.get("team_roles"):
        L += ["### 팀 역할 분담"] + [f"- {x}" for x in _as_lines(idea["team_roles"])] + [""]
    for h, key in [("신규성", "novelty"), ("기존 제품 대비", "why_not_existing_product"),
                   ("기대효과", "impact")]:
        if idea.get(key):
            L += [f"### {h}", str(idea[key]), ""]
    if idea.get("grounded_papers"):
        L += ["### 근거 논문"] + [f"- {x}" for x in _as_lines(idea["grounded_papers"])] + [""]
    if idea.get("difficulty"):
        L += [f"**난이도**: {idea['difficulty']}", ""]
    if verdict:
        L += ["### 적대 검증"]
        for label, key in [("기존제품 답습", "prior_art"), ("기술 타당성", "technical_soundness"),
                           ("인용·동향", "citation_trend"), ("실현가능성", "feasibility")]:
            val = verdict.get(key)
            if isinstance(val, dict):
                L.append(f"- **{label}**: {json.dumps(val, ensure_ascii=False)}")
        if verdict.get("verdict"):
            L.append(f"- **판정**: {verdict['verdict']}")
        if verdict.get("suggested_fix"):
            L += ["", "**보완 제안**", f"> {verdict['suggested_fix']}"]
        L.append("")
    return L


def render_markdown(contest: dict, papers: list[dict], result: dict,
                    verdicts: list[dict], out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    ideas_dir = out_dir / "ideas"
    ideas_dir.mkdir(exist_ok=True)
    selected = result.get("selected", [])
    vmap = {v.get("idea_title"): v for v in verdicts}

    R: list[str] = [
        f"# {contest.get('name','공모전')} — 아이디어 {len(selected)}종",
        "",
        "> Generated by **contest-idea-forge**. 각 아이디어는 근거 논문과 적대적 검증 결과를 포함합니다.",
        "",
        "## 1. 공모전 개요",
        *_overview_table(contest),
        "",
        "## 2. 선정 아이디어",
        "| # | 아이디어 | 난이도 | 한 줄 소개 |",
        "| --- | --- | --- | --- |",
    ]
    for i, idea in enumerate(selected):
        R.append(f"| {CIRCLED[i] if i < len(CIRCLED) else i+1} | {_esc(idea.get('title'))} "
                 f"| {_esc(idea.get('difficulty'))} | {_esc(idea.get('one_liner'))} |")
    R.append("")
    if result.get("selection_rationale"):
        R += ["## 3. 선정 논리", f"> {result['selection_rationale']}", ""]
    if result.get("comparison_with_old"):
        R += ["## 4. 비교/우위", f"> {result['comparison_with_old']}", ""]
    if result.get("rejected"):
        R += ["## 5. 폐기 후보", "| 후보 | 사유 |", "| --- | --- |"]
        for rj in result["rejected"]:
            R.append(f"| {_esc(rj.get('title'))} | {_esc(rj.get('reason'))} |")
        R.append("")
    R += ["## 6. 참고 논문", "| # | 제목 | 출처 / 연도 | source |", "| --- | --- | --- | --- |"]
    for i, p in enumerate(papers, 1):
        cell = f"[{_esc(p.get('title'))}]({p['url']})" if p.get("url") else _esc(p.get("title"))
        R.append(f"| {i} | {cell} | {_esc(p.get('venue'))} ({_esc(p.get('year'))}) | {_esc(p.get('source'))} |")

    (out_dir / "report.md").write_text("\n".join(R) + "\n", encoding="utf-8")

    for i, idea in enumerate(selected):
        title = idea.get("title", f"idea {i+1}")
        body = "\n".join([f"# {CIRCLED[i] if i < len(CIRCLED) else i+1} {title}", ""]
                         + _idea_body(idea, vmap.get(title)))
        (ideas_dir / f"idea_{i+1:02d}.md").write_text(body + "\n", encoding="utf-8")
    return out_dir / "report.md"


def save_json(payload: dict, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / "result.json"
    p.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return p


# --- optional Notion export ----------------------------------------------
def _md_to_blocks(report_md: str) -> list[dict]:
    """Tiny Markdown -> Notion blocks converter (headings/bullets/quote/para).

    Table rows are kept verbatim as paragraphs; rich table blocks are out of
    scope for v0.1 (the Markdown report remains the source of truth).
    """
    blocks: list[dict] = []

    def rt(text: str) -> list[dict]:
        return [{"type": "text", "text": {"content": text[:1900]}}]

    for line in report_md.splitlines():
        s = line.rstrip()
        if not s:
            continue
        if s.startswith("### "):
            blocks.append({"type": "heading_3", "heading_3": {"rich_text": rt(s[4:])}})
        elif s.startswith("## "):
            blocks.append({"type": "heading_2", "heading_2": {"rich_text": rt(s[3:])}})
        elif s.startswith("# "):
            blocks.append({"type": "heading_1", "heading_1": {"rich_text": rt(s[2:])}})
        elif s.startswith("- "):
            blocks.append({"type": "bulleted_list_item",
                           "bulleted_list_item": {"rich_text": rt(s[2:])}})
        elif s.startswith("> "):
            blocks.append({"type": "quote", "quote": {"rich_text": rt(s[2:])}})
        else:
            blocks.append({"type": "paragraph", "paragraph": {"rich_text": rt(s)}})
    return blocks[:100]  # Notion caps children per request


def push_notion(title: str, report_md: str, *, parent_page_id: str | None = None,
                token: str | None = None) -> str | None:
    """Create a Notion page from the report. Returns the page URL or None.

    Reads NOTION_TOKEN / NOTION_PARENT_PAGE_ID from env when not passed.
    """
    token = token or os.environ.get("NOTION_TOKEN")
    parent = parent_page_id or os.environ.get("NOTION_PARENT_PAGE_ID")
    if not token or not parent:
        print("[notion] NOTION_TOKEN / NOTION_PARENT_PAGE_ID not set — skipping.")
        return None
    payload = {
        "parent": {"page_id": parent},
        "properties": {"title": [{"text": {"content": title[:200]}}]},
        "children": _md_to_blocks(report_md),
    }
    req = urllib.request.Request(
        "https://api.notion.com/v1/pages",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Notion-Version": "2022-06-28",
        }, method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.loads(resp.read())
        return data.get("url")
    except Exception as e:  # noqa: BLE001
        print(f"[notion] push failed: {e}")
        return None
